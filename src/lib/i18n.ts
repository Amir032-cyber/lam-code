export function translate(language: 'fr' | 'en', key: MessageKey, vars: Record<string, string> = {}): string {
  const template: string = MESSAGES[language][key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? '');
}
